#!/usr/bin/env python3
"""Model-check every spec in this folder.

For each module: the proposed design must satisfy every property at once;
the current design is checked one property at a time so each failure is
recorded with its counterexample length. Writes results.md.
usage: python3 run.py [Module ...]   (TLA2TOOLS=/path/to/tla2tools.jar)
"""
import os, re, subprocess, sys, tempfile, json
HERE = os.path.dirname(os.path.abspath(__file__))
JAR = os.environ.get('TLA2TOOLS', os.path.join(HERE, 'tla2tools.jar'))
MODELS = json.load(open(os.path.join(HERE, 'models.json')))

def tlc(module, design, consts, invariants, properties):
    cfg = ['CONSTANTS', f'  Design = "{design}"'] + [f'  {k} = {v}' for k, v in consts.items()]
    cfg += ['SPECIFICATION Spec']
    if invariants: cfg += ['INVARIANTS'] + ['  ' + i for i in invariants]
    if properties: cfg += ['PROPERTIES'] + ['  ' + p for p in properties]
    with tempfile.TemporaryDirectory() as tmp:
        path = os.path.join(tmp, 'm.cfg'); open(path, 'w').write('\n'.join(cfg) + '\n')
        r = subprocess.run(['java', '-XX:+UseParallelGC', '-cp', JAR, 'tlc2.TLC', '-config', path,
                            '-workers', '4', '-nowarning', '-noGenerateSpecTE', '-metadir', os.path.join(tmp, 'meta'),
                            os.path.join(HERE, module + '.tla')], capture_output=True, text=True, cwd=tmp)
    out = r.stdout + r.stderr
    states = re.findall(r'([\d,]+) distinct states found', out)
    if 'No error has been found' in out: return 'pass', None, states[-1] if states else '?', out
    m = re.search(r'Error: (Invariant \w+ is violated|Temporal properties were violated|Action property \w+ is violated|Deadlock reached)', out)
    trace = max(1, len(re.findall(r'^State \d+:', out, re.M)))
    return 'FAIL', (m.group(1) if m else out[-600:]), trace, out

def main(names):
    lines = ['# Model-checking results', '', 'Generated by `python3 run.py` with TLC (tla2tools 1.8.0).', '']
    ok = True
    for name in names:
        m = MODELS[name]; props = m['invariants'] + m['properties']
        lines += [f'## {name}', '', f'Constants: `{m["constants"]}`', '', '| Property | Current design | Proposed design |', '|---|---|---|']
        status, why, n, out = tlc(name, 'proposed', m['constants'], ['TypeOK'] + m['invariants'], m['properties'])
        print(name, 'proposed', status, why or n, flush=True)
        if status != 'pass':
            ok = False; print(out[-3000:])
        prop_status = 'holds' if status == 'pass' else f'**FAILS** ({why})'
        for p in props:
            inv = [p] if p in m['invariants'] else []
            pr = [p] if p in m['properties'] else []
            cs, cwhy, cn, _ = tlc(name, 'current', m['constants'], ['TypeOK'] + inv, pr)
            print(name, 'current', p, cs, cn, flush=True)
            cur = 'holds' if cs == 'pass' else f'violated ({cn}-state counterexample)'
            lines.append(f'| `{p}` | {cur} | {prop_status} |')
        lines += ['', f'Proposed, all properties together: {status}, {n if status=="pass" else ""} distinct states.', '']
    open(os.path.join(HERE, 'results.md'), 'w').write('\n'.join(lines) + '\n')
    sys.exit(0 if ok else 1)

if __name__ == '__main__':
    main(sys.argv[1:] or list(MODELS))
