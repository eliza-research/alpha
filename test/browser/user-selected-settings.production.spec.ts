import {test,expect} from '@playwright/test';

for(const viewport of [{width:390,height:844},{width:1280,height:900}]){
 test(`selected Settings navigation and preferences persist at ${viewport.width}`,async({page})=>{
  await page.setViewportSize(viewport);
  await page.addInitScript(()=>{
   localStorage.setItem('alpha.connection.selection.v1',JSON.stringify({kind:'offline'}));
   localStorage.setItem('alpha:startup-permission-walkthrough:v1',JSON.stringify({version:1,status:'completed',step:4}));
   (window as any).permissionPrompts=0;
   const refuse=async()=>{(window as any).permissionPrompts++;throw Error('Unexpected permission request');};
   if(navigator.mediaDevices)navigator.mediaDevices.getUserMedia=refuse;
   if(navigator.geolocation)navigator.geolocation.getCurrentPosition=()=>{(window as any).permissionPrompts++;};
   if(window.Notification)Notification.requestPermission=refuse;
  });
  const open=async()=>{await page.goto('/');await page.getByRole('button',{name:'Settings',exact:true}).click();};
  const panel=(name:string)=>page.locator(`[data-settings-page="${name}"]:not([inert])`);
  await open();
  const root=panel('Settings');
  for(const label of ['Account','General','Privacy','Apps','About'])await expect(root.getByRole('button',{name:label,exact:true})).toBeVisible();
  await expect(root.getByText('Voice & personality',{exact:true})).toHaveCount(0);
  await root.getByRole('button',{name:'Account',exact:true}).click();
  const signIn=page.getByRole('dialog',{name:'Alpha',exact:true});
  await expect(signIn).toBeVisible();
  await expect(signIn.getByRole('textbox')).toHaveCount(0);
  await signIn.getByRole('button',{name:'Back',exact:true}).click();
  const progress=await page.evaluate(()=>localStorage.getItem('alpha:startup-permission-walkthrough:v1'));
  await root.getByRole('button',{name:'Privacy',exact:true}).click();
  await panel('Privacy').getByRole('button',{name:'Permissions',exact:true}).click();
  await expect(panel('App permissions')).toBeVisible();
  await expect(page.locator('.alpha-startup-permissions')).toHaveCount(0);
  await expect(panel('App permissions').getByText('Camera',{exact:true})).toBeVisible();
  expect(await page.evaluate(()=>localStorage.getItem('alpha:startup-permission-walkthrough:v1'))).toBe(progress);
  expect(await page.evaluate(()=>(window as any).permissionPrompts)).toBe(0);
  await page.getByRole('button',{name:'Back to Privacy',exact:true}).click();
  await page.getByRole('button',{name:'Back to Settings',exact:true}).click();
  await root.getByRole('button',{name:'About',exact:true}).click();
  await panel('About').getByRole('button',{name:'Licenses',exact:true}).click();
  const notices=await (await page.request.get('/licenses/third-party-notices.json')).json();
  const notice=notices.find((item:{name:string})=>item.name==='lucide-react');
  expect(typeof notice?.text).toBe('string');expect(notice.text.length).toBeGreaterThan(100);
  await page.getByRole('searchbox',{name:'Search components',exact:true}).fill('lucide');
  await page.getByRole('button',{name:notice.name+' '+notice.version,exact:true}).click();
  await expect.poll(()=>panel('License details').locator('div').allTextContents()).toContain(notice.text);
  if(notice.source)await expect.poll(()=>panel('License details').locator('div').allTextContents()).toContain(notice.source);
  await page.getByRole('button',{name:'Back to licenses',exact:true}).click();
  await expect(page.getByRole('searchbox',{name:'Search components',exact:true})).toHaveValue('lucide');
  await page.getByRole('button',{name:'Back to About',exact:true}).click();
  await expect(panel('About').getByText('Alpha Phone',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Back to Settings',exact:true}).click();
  await root.getByRole('button',{name:'General',exact:true}).click();
  await panel('General').getByRole('button',{name:'Display',exact:true}).click();
  await expect(panel('Display').getByRole('slider')).toHaveCount(0);
  await panel('Display').getByRole('button',{name:'Text size: Large',exact:true}).click();
  await expect(panel('Display').getByRole('button',{name:'Text size: Large, selected',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Back to General',exact:true}).click();
  await panel('General').getByRole('button',{name:'Notifications',exact:true}).click();
  const alerts=panel('Notifications').getByRole('button',{name:'Allow alerts',exact:true});
  const before=await alerts.getAttribute('aria-pressed');
  await alerts.click();
  await expect(alerts).toHaveAttribute('aria-pressed',before==='true'?'false':'true');
  await expect(page.locator('[data-browser-settings]')).toHaveCount(0);
  await open();
  await root.getByRole('button',{name:'General',exact:true}).click();
  await panel('General').getByRole('button',{name:'Display',exact:true}).click();
  await expect(panel('Display').getByRole('button',{name:'Text size: Large, selected',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Back to General',exact:true}).click();
  await panel('General').getByRole('button',{name:'Notifications',exact:true}).click();
  await expect(panel('Notifications').getByRole('button',{name:'Allow alerts',exact:true})).toHaveAttribute('aria-pressed',before==='true'?'false':'true');
  await page.getByRole('button',{name:'Back to General',exact:true}).click();
  await page.getByRole('button',{name:'Back to Settings',exact:true}).click();
  await root.getByRole('button',{name:'Apps',exact:true}).click();
  await panel('Apps').getByRole('button',{name:'Inbox',exact:true}).click();
  await panel('Inbox').getByRole('button',{name:'Google & email',exact:true}).click();
  const manager=page.getByRole('dialog',{name:'Google accounts',exact:true});
  await expect(manager).toBeVisible();
  await expect(page.getByRole('dialog')).toHaveCount(1);
  const box=(await manager.boundingBox())!;
  expect(box.x).toBeGreaterThanOrEqual(0);expect(box.y).toBeGreaterThanOrEqual(0);
  expect(box.x+box.width).toBeLessThanOrEqual(viewport.width+1);
  expect(box.y+box.height).toBeLessThanOrEqual(viewport.height+1);
 });
}
